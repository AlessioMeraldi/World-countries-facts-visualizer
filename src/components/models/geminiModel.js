// imports
import { GoogleGenerativeAI } from "@google/generative-ai";

// local variables
const API_KEY = import.meta.env.VITE_GEMINI_API_KEY; // get (Gemini's) API key from Vite's ambient variables toDo: find the damned thing

// Begin logic
const genAI = new GoogleGenerativeAI(API_KEY); // initialize Gemini instance, if key is missing it throws an error (handled later)

/**
 * fetchGeminiResponse
 * Queries the Gemini Pro model with a simple text prompt.
 * @param {string} promptText - The question or instruction to send to Gemini.
 * @returns {Promise<string>} - The text response generated by the AI.
 */
export async function fetchGeminiResponse(promptText) {

    if (!API_KEY) {
        throw new Error("API Key missing, check the .env file"); // if API_KEY is not assigned, throw error and notify via console
    }

    // Gemini's response can throw an error if something goes wrong, code is put within try{}catch(){} to handle it
    try {
        const model = genAI.getGenerativeModel({ model: "gemini-2.5-flash-lite" }); // define variabile that specifies which Gemini model to interrogate (there's multiple versions)
        // Note: at time of writing, this model has 10 free interrogations daily

        const serverResponse = await model.generateContent(promptText); // send request / prompt to the Gemini model and await response
        const unpackedData = await serverResponse.response; // data unpacking is asynchronous, we must put another 'await' for it to have finished unpacking
        const textResponse = unpackedData.text(); // convenience variable to return the text

        return textResponse;

    } catch (error) {
        console.error("Error during Gemini calling: ", error); // log error in the console directly
        throw new Error("Impossibile ottenere una risposta da Gemini al momento."); // signal (forward) the error to the ViewModel
    }
}
